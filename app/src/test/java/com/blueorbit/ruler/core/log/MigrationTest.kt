package com.blueorbit.ruler.core.log

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * M11R finding 2: the migration SQL and the entity's expected DDL are two independently written
 * strings. Room validates the migrated table against the *exported schema*, so the test reads that
 * JSON and cross-checks the entity annotation, the exported `createSql` and the migration constant
 * against each other. A column change that updates only one of the three is what this catches.
 *
 * The JSON is read as text rather than parsed (no `org.json` on the unit-test classpath).
 */
class MigrationTest {

    /** The exported schema for the current version, written by `assembleDebug`/`assembleRelease`. */
    private fun exportedSchemaText(): String {
        val relative = "schemas/com.blueorbit.ruler.core.log.AppDatabase/${AppDatabase.VERSION}.json"
        val file = generateSequence(File(System.getProperty("user.dir")!!)) { it.parentFile }
            .take(4)
            .map { File(it, relative) }
            .firstOrNull { it.isFile }
        assertNotNull("exported schema not found at $relative — run ./gradlew assembleDebug first", file)
        return file!!.readText()
    }

    /** The exact `DEFAULT ...` clause the migration appends to the `tags` column. */
    private val migrationTagsDefault: String = Migrations.ADD_TAGS_SQL.substringAfter("DEFAULT ").trim()

    @Test
    fun v1ToV2UpgradesFromVersion1ToVersion2() {
        assertEquals(1, Migrations.v1ToV2.startVersion)
        assertEquals(2, Migrations.v1ToV2.endVersion)
    }

    @Test
    fun theDatabaseVersionMatchesTheLastMigration() {
        assertEquals(AppDatabase.VERSION, Migrations.all.last().endVersion)
    }

    @Test
    fun theExportedColumnUsesTheSameDefaultAsTheMigration() {
        // The exported schema is generated by KSP from the entity's `@ColumnInfo(defaultValue = "")`,
        // which is not runtime-retained and so cannot be read by reflection. If the annotation is
        // dropped, KSP regenerates this file without the default and the test fails.
        val schema = exportedSchemaText()
        val column = Regex("\"columnName\": \"tags\",[\\s\\S]*?\"defaultValue\": \"('[^']*')\"")
            .find(schema)
        assertNotNull("tags has no defaultValue in the exported schema", column)
        assertEquals(migrationTagsDefault, column!!.groupValues[1])
    }

    @Test
    fun theExportedCreateSqlUsesTheSameDefaultAsTheMigration() {
        val exported = Regex("`tags` TEXT NOT NULL DEFAULT ('[^']*')")
            .find(exportedSchemaText())
        assertNotNull("tags has no DEFAULT in the exported createSql", exported)
        assertEquals(migrationTagsDefault, exported!!.groupValues[1])
    }

    @Test
    fun existingRowsReadBackAsAnEmptyTagsValue() {
        // A pre-v2 row gets '' from the migration DEFAULT; the default constructor agrees, so the
        // reader never sees null for a column the entity declares as non-null.
        assertEquals("''", migrationTagsDefault)
        assertTrue(Measurement(0, 0, "MM", "", "", "", 0.0, 0).tags.isEmpty())
    }
}
